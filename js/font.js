function tinyWidth(str) {
  str = String(str);
  return str.length ? str.length * 4 - 1 : 0;
}

function drawTiny(str, x, y, color = PAL.white, opts = {}) {
  str = String(str).toUpperCase();
  const w = tinyWidth(str);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  const key = `tiny\u0000${str}\u0000${color}`;
  let c = textCache.get(key);
  if (!c) {
    c = document.createElement('canvas');
    c.width = Math.max(1, w); c.height = 5;
    const g = c.getContext('2d');
    g.fillStyle = color;
    for (let i = 0; i < str.length; i++) {
      const glyph = TINY[str[i]];
      if (!glyph) continue;
      for (let gy = 0; gy < 5; gy++) for (let gx = 0; gx < 3; gx++) if (glyph[gy][gx] === '#') g.fillRect(i * 4 + gx, gy, 1, 1);
    }
    if (textCache.size > 1000) textCache.clear();
    textCache.set(key, c);
  }
  ctx.drawImage(c, Math.round(x), Math.round(y));
  return w;
}

function wrapText(str, max) {
  const lines = [];
  let line = '';
  for (const word of String(str).split(' ')) {
    const next = line ? `${line} ${word}` : word;
    if (next.length > max && line) { lines.push(line); line = word; } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
