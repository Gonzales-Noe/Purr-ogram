const FONT = {};
for (const ch in GLYPHS) FONT[ch] = GLYPHS[ch].split('|');

const textCache = new Map();

function textWidth(str, scale = 1) {
  str = String(str);
  return str.length ? (str.length * 6 - 1) * scale : 0;
}

function renderText(str, color, scale) {
  const key = `${str}\u0000${color}\u0000${scale}`;
  let c = textCache.get(key);
  if (c) return c;
  c = document.createElement('canvas');
  c.width = Math.max(1, textWidth(str, scale));
  c.height = 7 * scale;
  const g = c.getContext('2d');
  g.fillStyle = color;
  for (let i = 0; i < str.length; i++) {
    const glyph = FONT[str[i]];
    if (!glyph) continue;
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        if (glyph[y][x] === '#') g.fillRect((i * 6 + x) * scale, y * scale, scale, scale);
      }
    }
  }
  if (textCache.size > 1000) textCache.clear();
  textCache.set(key, c);
  return c;
}

function drawText(str, x, y, color = PAL.white, opts = {}) {
  str = String(str).toUpperCase();
  const scale = opts.scale || 1, g = opts.ctx || ctx;
  const w = textWidth(str, scale);
  if (opts.align === 'center') x -= Math.floor(w / 2);
  else if (opts.align === 'right') x -= w;
  x = Math.round(x); y = Math.round(y);
  if (opts.shadow) g.drawImage(renderText(str, opts.shadow, scale), x + scale, y + scale);
  g.drawImage(renderText(str, color, scale), x, y);
  return w;
}

